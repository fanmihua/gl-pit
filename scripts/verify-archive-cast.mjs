import { writeFile } from "node:fs/promises";
import { archiveDramas } from "../src/data/archive-dramas.js";

const GRAPHQL_ENDPOINT = "https://gl-spotlight-production.fly.dev/graphql";
const VERIFIED_AT = new Date().toISOString();
const WRITE = process.argv.includes("--write");
const CONCURRENCY = 6;

const seriesQuery = `
  query SeriesBySlug($slug: String!) {
    seriesBySlug(slug: $slug) { id name slug }
  }
`;

const castQuery = `
  query SeriesCast($seriesId: ID!) {
    seriesCast(
      seriesId: $seriesId
      cursorPaginationInput: { direction: FORWARD, limit: 20 }
    ) {
      edges {
        node {
          character { role }
          actress { knownAs name }
        }
      }
    }
  }
`;

async function request(query, variables) {
  const response = await fetch(GRAPHQL_ENDPOINT, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ query, variables }),
  });
  if (!response.ok) throw new Error(`GraphQL HTTP ${response.status}`);
  const payload = await response.json();
  if (payload.errors?.length) throw new Error(payload.errors.map((error) => error.message).join("; "));
  return payload.data;
}

async function verifyDrama(drama) {
  const slug = new URL(drama.sourceUrl).pathname.split("/").filter(Boolean).at(-1);
  const seriesData = await request(seriesQuery, { slug });
  const series = seriesData.seriesBySlug;
  if (!series) throw new Error(`Series not found for ${slug}`);

  const castData = await request(castQuery, { seriesId: series.id });
  const mainCast = castData.seriesCast.edges
    .filter((edge) => edge.node.character.role === "MAIN")
    .map((edge) => edge.node.actress)
    .map((actress) => {
      const knownAs = actress.knownAs?.trim() || "";
      const name = actress.name.trim();
      const nameStartsWithKnownAs = knownAs
        && name.toLocaleLowerCase("en").startsWith(`${knownAs.toLocaleLowerCase("en")} `);
      return {
        displayName: knownAs && !nameStartsWithKnownAs ? `${knownAs} ${name}` : name,
        knownAs,
        name,
      };
    });

  return {
    id: drama.id,
    title: drama.title,
    titleEn: drama.titleEn,
    year: drama.year,
    sourceUrl: drama.sourceUrl,
    sourceApi: GRAPHQL_ENDPOINT,
    sourceSeriesId: series.id,
    verifiedAt: VERIFIED_AT,
    castStatus: mainCast.length ? "verified" : "not-listed",
    mainCast,
  };
}

async function runPool(items, worker) {
  const results = new Array(items.length);
  let cursor = 0;
  async function run() {
    while (cursor < items.length) {
      const index = cursor;
      cursor += 1;
      try {
        results[index] = await worker(items[index]);
      } catch (error) {
        results[index] = {
          id: items[index].id,
          title: items[index].title,
          titleEn: items[index].titleEn,
          year: items[index].year,
          sourceUrl: items[index].sourceUrl,
          sourceApi: GRAPHQL_ENDPOINT,
          verifiedAt: VERIFIED_AT,
          castStatus: "error",
          error: error instanceof Error ? error.message : String(error),
          mainCast: [],
        };
      }
    }
  }
  await Promise.all(Array.from({ length: CONCURRENCY }, run));
  return results;
}

const records = await runPool(archiveDramas, verifyDrama);
const castMap = Object.fromEntries(
  records
    .filter((record) => record.castStatus === "verified")
    .map((record) => [record.id, record.mainCast.map((actress) => actress.displayName)]),
);

const summary = {
  total: records.length,
  verified: records.filter((record) => record.castStatus === "verified").length,
  notListed: records.filter((record) => record.castStatus === "not-listed").length,
  errors: records.filter((record) => record.castStatus === "error").length,
};

if (WRITE) {
  const moduleSource = `// Generated by scripts/verify-archive-cast.mjs on ${VERIFIED_AT}\nexport const archiveMainCastById = ${JSON.stringify(castMap, null, 2)};\n`;
  const auditSource = `${JSON.stringify({ verifiedAt: VERIFIED_AT, sourceApi: GRAPHQL_ENDPOINT, summary, records }, null, 2)}\n`;
  await writeFile(new URL("../src/data/archive-cast.js", import.meta.url), moduleSource);
  await writeFile(new URL("../docs/archive-cast-verification.json", import.meta.url), auditSource);
}

process.stdout.write(`${JSON.stringify({ summary, unresolved: records.filter((record) => record.castStatus !== "verified") }, null, 2)}\n`);
